def crc16_modbus(data: bytes) -> int:
    """Return CRC-16/MODBUS for deterministic serial-frame validation."""
    crc = 0xFFFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            if crc & 0x0001:
                crc = (crc >> 1) ^ 0xA001
            else:
                crc >>= 1
    return crc & 0xFFFF
